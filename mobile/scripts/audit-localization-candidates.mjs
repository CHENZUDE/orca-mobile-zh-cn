// Why regex+fs walk instead of desktop's AST scan or a ripgrep wrapper:
// the mobile tree is small enough for line-level regexes, and Node 24 + Windows
// silently drops the cwd override when ripgrep is spawned under a CJK path.

import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const ROOT = path.resolve(process.cwd());
const MOBILE = path.join(ROOT, "mobile");
const CANDIDATE_DIRS = [path.join(MOBILE, "src"), path.join(MOBILE, "app")];
const SKIP_DIRS = new Set(["node_modules", ".git", "__snapshots__", "dist", "fixtures", "__mocks__", "rpc-foundation"]);

const PATTERNS = [
  {
    "id": "jsx-text",
    "description": "JSX text node >English<",
    "regex": ">([A-Za-z][^<>{}]{3,120})<"
  },
  {
    "id": "placeholder",
    "description": "placeholder= string literal",
    "regex": "placeholder=[\"']([^\"']+)[\"']"
  },
  {
    "id": "accessibility",
    "description": "accessibilityLabel= string literal",
    "regex": "accessibilityLabel=[\"']([^\"']+)[\"']"
  },
  {
    "id": "stack-title",
    "description": "title: <string> in JS options object",
    "regex": "title:\\s*[\"']([^\"']+)[\"']"
  },
  {
    "id": "menu-label",
    "description": "label: <string> in object",
    "regex": "label:\\s*[\"']([^\"']+)[\"']"
  },
  {
    "id": "data-title-desc",
    "description": "{ title: ..., desc: ... } data entry",
    "regex": "title:\\s*[\"']([^\"']+)[\"'],\\s*desc:\\s*[\"']"
  },
  {
    "id": "alert-call",
    "description": "Alert.alert(<str>, ...) string literal",
    "regex": "Alert\\.alert\\([\"']([^\"']+)[\"']"
  }
];

const HIGH_PRIORITY_MODULES = new Set(["app","home","pairing","onboarding","settings","diagnostics","notifications","about"]);
const LOW_PRIORITY_MODULES = new Set(["test-support","__mocks__","fixtures","rpc-foundation"]);

function moduleFromPath(relativeFile) {
  const parts = relativeFile.split("/");
  if (parts[0] === "mobile" && parts[1] === "app") {
    return "app"
  }
  if (parts[0] === "mobile" && parts[1] === "src") {
    // parts[2] is a module folder only when there is a parts[3] (i.e. it
    // nests a file inside it). bare files at mobile/src/<file> get the
    // "src-top" bucket so priorityFor keeps them out of the high list.
    return parts[3] ? parts[2] : "src-top";
  }
  return "unknown";
}

function priorityFor(module) {
  if (LOW_PRIORITY_MODULES.has(module)) {
    return "low"
  }
  if (HIGH_PRIORITY_MODULES.has(module)) {
    return "high"
  }
  return "medium";
}

async function walk(dir) {
  const out = [];
  let entries;
  try { entries = await fs.readdir(dir, { withFileTypes: true }); } catch { return out; }
  for (const entry of entries) {
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) {
        continue
      }
      out.push(...(await walk(path.join(dir, entry.name))));
    } else if (/\.(ts|tsx|js|jsx|mts|cts)$/.test(entry.name)) {
      out.push(path.join(dir, entry.name));
    }
  }
  return out;
}

function sanitize(s) { return s.replace(/\s+/g, " ").trim().slice(0, 200); }

async function scan() {
  const compiled = PATTERNS.map((p) => ({ ...p, re: new RegExp(p.regex, "g") }));
  const hits = [];
  for (const dir of CANDIDATE_DIRS) {
    const files = await walk(dir);
    for (const file of files) {
      const text = await fs.readFile(file, "utf8");
      const lines = text.split("\n");
      for (let i = 0; i < lines.length; i++) {
        const line = lines[i];
        for (const pat of compiled) {
          pat.re.lastIndex = 0;
          let m;
          while ((m = pat.re.exec(line)) !== null) {
            // POSIX-style rel path so Markdown tables don't render \s as escapes.
            const rel = path.relative(ROOT, file).split(path.sep).join("/");
            hits.push({
              pattern: pat.id,
              module: moduleFromPath(rel),
              file: rel,
              line: i + 1,
              text: sanitize(m[1] ?? m[0]),
              priority: priorityFor(moduleFromPath(rel))
            });
          }
        }
      }
    }
  }
  return hits;
}

function escapeCell(text) {
  return text.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim().slice(0, 200);
}

function toMarkdown(hits) {
  const byModule = new Map();
  for (const h of hits) {
    if (!byModule.has(h.module)) {
      byModule.set(h.module, [])
    }
    byModule.get(h.module).push(h);
  }
  const lines = [];
  lines.push("# Mobile i18n Candidate Inventory");
  lines.push("");
  lines.push("Generated by mobile/scripts/audit-localization-candidates.mjs.");
  lines.push("Total hits: **" + hits.length + "** across **" + byModule.size + "** modules.");
  lines.push("");
  const totals = { high: 0, medium: 0, low: 0 };
  for (const h of hits) {
    totals[h.priority]++
  }
  lines.push("- High: " + totals.high);
  lines.push("- Medium: " + totals.medium);
  lines.push("- Low: " + totals.low);
  lines.push("");
  lines.push("Priority rules: HIGH = app, home, pairing, onboarding, settings, diagnostics, notifications, about. LOW = test-support, __mocks__, fixtures, rpc-foundation. Anything else is MEDIUM.");
  lines.push("");
  const sorted = [...byModule.keys()].sort();
  for (const m of sorted) {
    const moduleHits = byModule.get(m);
    lines.push("## " + m + " (" + moduleHits.length + ")");
    lines.push("");
    lines.push("| Prio | Pattern | File:Line | Sample |");
    lines.push("|---|---|---|---|");
    moduleHits.sort((a, b) => (a.priority < b.priority ? -1 : a.priority > b.priority ? 1 : a.line - b.line));
    for (const h of moduleHits) {
      lines.push("| " + h.priority + " | " + h.pattern + " | {" + escapeCell(h.file) + ":" + h.line + "} | {" + escapeCell(h.text) + "} |");
    }
    lines.push("");
  }
  return lines.join("\n");
}

async function main() {
  const hits = await scan();
  const outJson = path.join(".tmp", "mobile-i18n", "candidates", "raw.json");
  const outMd = path.join("mobile", "docs", "i18n-candidates.md");
  await fs.mkdir(path.dirname(outJson), { recursive: true });
  await fs.mkdir(path.dirname(outMd), { recursive: true });
  await fs.writeFile(outJson, JSON.stringify(hits, null, 2) + "\n");
  await fs.writeFile(outMd, toMarkdown(hits));
  console.log("Wrote " + hits.length + " hits to " + outJson + " and " + outMd);
}

await main();
